val downloadAndExtractFrpc by tasks.registering {
    val destDirBase = file("src/main/jniLibs")
    
    outputs.dir(destDirBase)
    notCompatibleWithConfigurationCache("Requires script objects")
    
    doLast {
        val abis = mapOf(
            "arm64-v8a" to "arm64",
            "armeabi-v7a" to "arm",
            "x86_64" to "amd64"
        )
        
        abis.forEach { (abi, arch) ->
            val destDir = file("src/main/jniLibs/$abi")
            destDir.mkdirs()
            
            val tarGzFile = layout.buildDirectory.file("tmp/frpc_$abi.tar.gz").get().asFile
            if (!tarGzFile.exists()) {
                tarGzFile.parentFile.mkdirs()
                URL("https://github.com/fatedier/frp/releases/download/v0.61.1/frp_0.61.1_linux_$arch.tar.gz").openStream().use { input ->
                    FileOutputStream(tarGzFile).use { output ->
                        input.copyTo(output)
                    }
                }
            }
            
            copy {
                from(tarTree(resources.gzip(tarGzFile)))
                into(destDir)
                include("*/frpc")
                eachFile {
                    path = "libfrpc.so"
                }
                includeEmptyDirs = false
            }
            println("FRPC embedded into libfrpc.so for $abi")
        }
    }
}

tasks.named("preBuild") {
    dependsOn(downloadAndExtractFrpc)
}

